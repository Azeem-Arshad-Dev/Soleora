"""Builds the self-hosted font subsets in src/fonts/ and src/css/fonts.css.
Usage: python3 tools/subset-fonts.py   (needs: pip install fonttools brotli)
Sources are the Latin variable files from @fontsource-variable (all axes kept: weight, width and
optical size for Bricolage; weight and optical size for Source Serif 4). Only the code points listed in
src/fonts/subset.json are kept, with every OpenType layout feature."""
import json, pathlib, subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
FS = ROOT / 'node_modules/@fontsource-variable'
UNICODES = json.loads((ROOT / 'src/fonts/subset.json').read_text())['unicodes']
FACES = [
    dict(family='Bricolage Grotesque Variable', src=FS / 'bricolage-grotesque/files/bricolage-grotesque-latin-standard-normal.woff2',
         out='bricolage-grotesque-subset.woff2', weight='200 800', stretch='75% 100%'),
    dict(family='Source Serif 4 Variable', src=FS / 'source-serif-4/files/source-serif-4-latin-opsz-normal.woff2',
         out='source-serif-4-subset.woff2', weight='200 900', stretch=None),
]
css = ['/* Generated by tools/subset-fonts.py from @fontsource-variable (OFL-1.1). Do not edit by hand. */']
for f in FACES:
    dst = ROOT / 'src/fonts' / f['out']
    subprocess.run(['pyftsubset', str(f['src']), f'--unicodes={UNICODES}', '--layout-features=*',
                    '--flavor=woff2', f'--output-file={dst}'], check=True)
    print(f"{f['out']}: {f['src'].stat().st_size} -> {dst.stat().st_size} bytes")
    css.append('@font-face {\n'
               f"  font-family: '{f['family']}';\n  font-style: normal;\n  font-display: swap;\n  font-weight: {f['weight']};\n"
               + (f"  font-stretch: {f['stretch']};\n" if f['stretch'] else '')
               + f"  src: url('../fonts/{f['out']}') format('woff2-variations');\n  unicode-range: {UNICODES};\n}}")
(ROOT / 'src/css/fonts.css').write_text('\n'.join(css) + '\n')
